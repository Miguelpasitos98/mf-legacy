const LEFT=new Set(["LB","LI","DL","LWB","CAI","CRI","EI","LW","LM","DEFENSA_IZQUIERDO","CARRILERO_IZQUIERDO","MEDIAPUNTA_POR_LA_IZQUIERDA","CENTROCAMPISTA_IZQUIERDO"]);
